-- Watchlist versions are immutable: a new upload always creates a new version row + new entry rows.
-- The current version is the most recently loaded one (highest id); nothing is ever updated in place.
CREATE TABLE watchlist_version (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_filename VARCHAR(255),
    entry_count     INTEGER                  NOT NULL,
    loaded_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    loaded_by       VARCHAR(100)             NOT NULL
);

-- Sequence (not identity) so Hibernate can batch the ~2,000 entry inserts of an upload.
CREATE SEQUENCE watchlist_entry_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE watchlist_entry (
    id           BIGINT       PRIMARY KEY,
    version_id   BIGINT       NOT NULL REFERENCES watchlist_version (id),
    entry_ref    VARCHAR(64)  NOT NULL,
    primary_name VARCHAR(255) NOT NULL,
    dob          DATE,
    nationality  VARCHAR(2),
    list_type    VARCHAR(20)  NOT NULL,
    CONSTRAINT uq_watchlist_entry_ref_per_version UNIQUE (version_id, entry_ref)
);

CREATE TABLE watchlist_entry_alias (
    entry_id BIGINT       NOT NULL REFERENCES watchlist_entry (id),
    alias    VARCHAR(255) NOT NULL
);
CREATE INDEX idx_watchlist_entry_alias_entry ON watchlist_entry_alias (entry_id);

CREATE TABLE screening (
    id                   UUID                     PRIMARY KEY,
    customer_ref         VARCHAR(64)              NOT NULL,
    full_name            VARCHAR(255)             NOT NULL,
    dob                  DATE,
    nationality          VARCHAR(2),
    watchlist_version_id BIGINT                   NOT NULL REFERENCES watchlist_version (id),
    decision             VARCHAR(20)              NOT NULL,
    cache_hit            BOOLEAN                  NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_screening_customer_ref ON screening (customer_ref);

CREATE TABLE screening_hit (
    id                 UUID                     PRIMARY KEY,
    screening_id       UUID                     NOT NULL REFERENCES screening (id),
    watchlist_entry_id BIGINT                   NOT NULL REFERENCES watchlist_entry (id),
    matched_name       VARCHAR(255)             NOT NULL,
    matched_on         VARCHAR(10)              NOT NULL,
    score              DOUBLE PRECISION         NOT NULL,
    status             VARCHAR(20)              NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    row_version        BIGINT                   NOT NULL DEFAULT 0
);
-- Review queue: WHERE status = ? ORDER BY created_at DESC LIMIT ? OFFSET ?
CREATE INDEX idx_screening_hit_status_created_at ON screening_hit (status, created_at DESC);
CREATE INDEX idx_screening_hit_screening ON screening_hit (screening_id);
