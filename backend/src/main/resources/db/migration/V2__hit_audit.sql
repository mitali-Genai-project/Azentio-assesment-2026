-- Append-only audit trail of hit dispositions. The application only ever INSERTs into this table
-- (no update/delete paths exist); in production, also REVOKE UPDATE, DELETE from the application role.
CREATE TABLE hit_audit_record (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hit_id      UUID                     NOT NULL REFERENCES screening_hit (id),
    from_status VARCHAR(20)              NOT NULL,
    to_status   VARCHAR(20)              NOT NULL,
    actor       VARCHAR(100)             NOT NULL,
    actor_role  VARCHAR(20)              NOT NULL,
    reason      VARCHAR(1000)            NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_hit_audit_record_hit_created ON hit_audit_record (hit_id, created_at);
