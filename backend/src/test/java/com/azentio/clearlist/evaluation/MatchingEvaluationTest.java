package com.azentio.clearlist.evaluation;

import static org.assertj.core.api.Assertions.assertThat;

import com.azentio.clearlist.dto.HitResponse;
import com.azentio.clearlist.dto.ScreeningRequest;
import com.azentio.clearlist.dto.ScreeningResponse;
import com.azentio.clearlist.service.ScreeningService;
import com.azentio.clearlist.service.WatchlistService;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;
import org.apache.commons.csv.CSVFormat;
import org.apache.commons.csv.CSVParser;
import org.apache.commons.csv.CSVRecord;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.ActiveProfiles;

/**
 * Runs the labelled evaluation dataset (generated by scripts/generate_watchlist.py) through the real
 * upload + screening pipeline with the production matching configuration.
 *
 * <ul>
 *   <li>Recall: a true-match row counts as found when its expected entry is among the hits.</li>
 *   <li>False-positive rate: a NONE row counts as a false positive when it produces any hit at all.</li>
 * </ul>
 */
@SpringBootTest
@ActiveProfiles("test")
class MatchingEvaluationTest {

    private static final double MIN_RECALL = 0.90;
    private static final double MAX_FALSE_POSITIVE_RATE = 0.10;

    @Autowired
    private WatchlistService watchlistService;

    @Autowired
    private ScreeningService screeningService;

    @Test
    void recallAndFalsePositiveRateMeetTargets() throws IOException {
        watchlistService.upload("watchlist.csv", "text/csv", readResource("/data/watchlist.csv"), "evaluation");
        List<CSVRecord> cases = readEvaluationCases();

        int positives = 0;
        int truePositives = 0;
        int negatives = 0;
        int falsePositives = 0;
        List<String> failures = new ArrayList<>();

        for (CSVRecord row : cases) {
            String expected = row.get("expectedEntryId");
            ScreeningResponse response = screeningService.screen(new ScreeningRequest(
                    row.get("caseId"), row.get("customerName"), parseDate(row.get("dob")), null));
            List<String> hitIds = response.topHits().stream().map(HitResponse::entryId).toList();

            if ("NONE".equals(expected)) {
                negatives++;
                if (!hitIds.isEmpty()) {
                    falsePositives++;
                    failures.add("FALSE POSITIVE " + describe(row) + " -> " + summarize(response.topHits()));
                }
            } else {
                positives++;
                if (response.totalHits() > response.topHits().size()) {
                    // Expected entry might be beyond the response cap; this dataset should never need that.
                    failures.add("NOTE " + describe(row) + " has " + response.totalHits() + " hits (capped)");
                }
                if (hitIds.contains(expected)) {
                    truePositives++;
                } else {
                    failures.add("MISSED " + describe(row) + " expected " + expected + " -> "
                            + summarize(response.topHits()));
                }
            }
        }

        double recall = (double) truePositives / positives;
        double falsePositiveRate = (double) falsePositives / negatives;
        System.out.printf("%n=== Matching evaluation ===%n");
        System.out.printf("true-match rows: %d, found: %d, recall: %.3f%n", positives, truePositives, recall);
        System.out.printf("NONE rows: %d, false positives: %d, false-positive rate: %.3f%n",
                negatives, falsePositives, falsePositiveRate);
        failures.forEach(f -> System.out.println("  " + f));

        assertThat(positives).isGreaterThanOrEqualTo(30);
        assertThat(negatives).isGreaterThanOrEqualTo(20);
        assertThat(recall).as("recall").isGreaterThanOrEqualTo(MIN_RECALL);
        assertThat(falsePositiveRate).as("false-positive rate").isLessThanOrEqualTo(MAX_FALSE_POSITIVE_RATE);
    }

    private static String describe(CSVRecord row) {
        return row.get("caseId") + " [" + row.get("variantType") + "] '" + row.get("customerName") + "'";
    }

    private static String summarize(List<HitResponse> hits) {
        return hits.stream().limit(3).map(h -> h.entryId() + " '" + h.matchedName() + "' " + h.score()).toList()
                .toString();
    }

    private static LocalDate parseDate(String value) {
        return value == null || value.isBlank() ? null : LocalDate.parse(value);
    }

    private List<CSVRecord> readEvaluationCases() throws IOException {
        try (InputStream in = getClass().getResourceAsStream("/data/evaluation.csv");
             CSVParser parser = CSVParser.parse(new InputStreamReader(in, StandardCharsets.UTF_8),
                     CSVFormat.DEFAULT.builder().setHeader().setSkipHeaderRecord(true).build())) {
            return parser.getRecords();
        }
    }

    private byte[] readResource(String path) throws IOException {
        try (InputStream in = getClass().getResourceAsStream(path)) {
            assertThat(in).as("test resource %s (run scripts/generate_watchlist.py)", path).isNotNull();
            return in.readAllBytes();
        }
    }
}
